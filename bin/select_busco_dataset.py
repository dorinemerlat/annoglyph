#!/usr/bin/env python3
"""Select the most specific BUSCO dataset for each taxonomy."""

import argparse
import re
import subprocess
from pathlib import Path

import pandas as pd


DATASET_PATTERN = re.compile(r"-\s+(\S+)\s+\[\d+\]")
DATASET_VERSION_PATTERN = re.compile(r"(_odb\d+)\.\d+$")

METADATA_COLUMNS = {
    "id",
    "name",
    "taxonomy",
    "taxid",
    "official_mnemonic",
    "exogap_mnemonic",
}


def parse_args():
    parser = argparse.ArgumentParser(description="Select BUSCO datasets from a taxonomy table.")
    parser.add_argument("--taxonomy", required=True, type=Path, help="Taxonomy TSV generated by generate_taxonomy_metadata.py.")
    parser.add_argument("--output", default=Path("busco_datasets.tsv"), type=Path, help="Output BUSCO datasets TSV.")
    return parser.parse_args()


def list_busco_datasets():
    """Return available BUSCO datasets."""
    result = subprocess.run(
        ["busco", "--list-datasets"],
        check=True,
        capture_output=True,
        text=True,
    )

    datasets = {}

    for line in result.stdout.splitlines():
        match = DATASET_PATTERN.search(line)

        if not match:
            continue

        dataset = DATASET_VERSION_PATTERN.sub(r"\1", match.group(1))
        taxon_name = dataset.rsplit("_odb", 1)[0].replace("_", " ")
        datasets[taxon_name.lower()] = dataset

    return datasets


def find_matching_dataset(row, rank_columns, available_datasets):
    """Return the most specific BUSCO dataset matching a taxonomy."""
    for rank in reversed(rank_columns):
        taxon_name = str(row[rank]).strip().lower()

        if not taxon_name:
            continue

        dataset = available_datasets.get(taxon_name)

        if dataset:
            return dataset

    return None


def main():
    args = parse_args()

    taxonomy = pd.read_csv(args.taxonomy, sep="\t", dtype=str, keep_default_na=False)
    rank_columns = [column for column in taxonomy.columns if column not in METADATA_COLUMNS]
    available_datasets = list_busco_datasets()
    rows = []

    for _, row in taxonomy.iterrows():
        dataset = find_matching_dataset(row, rank_columns, available_datasets)

        if not dataset:
            raise ValueError(f"No matching BUSCO dataset found for '{row['id']}'.")

        rows.append(
            {
                "id": row["id"],
                "busco_dataset": dataset,
            }
        )

    pd.DataFrame(rows).to_csv(args.output, sep="\t", index=False)


if __name__ == "__main__":
    main()