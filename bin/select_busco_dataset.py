#!/usr/bin/env python3
"""Select one shared BUSCO dataset for all input taxa."""

import argparse
import re
import subprocess
from pathlib import Path
import pandas as pd


DATASET_PATTERN = re.compile(r"\b([A-Za-z0-9_]+_odb\d+)(?:\.\d+)?\b")

METADATA_COLUMNS = {
    "id",
    "name",
    "taxonomy",
    "taxid",
    "official_mnemonic",
    "annoglyph_mnemonic",
}


def parse_args():
    parser = argparse.ArgumentParser(description="Select one BUSCO dataset shared by all taxa.")
    parser.add_argument("--taxonomy", required=True, type=Path, help="Taxonomy TSV generated by generate_taxonomy_metadata.py.")
    parser.add_argument("--output", type=Path, help="Optional output file containing the selected BUSCO dataset.")
    return parser.parse_args()


def list_busco_datasets():
    """Return available BUSCO datasets indexed by taxon name."""
    result = subprocess.run(
        ["busco", "--list-datasets"],
        check=True,
        capture_output=True,
        text=True,
    )

    datasets = {}

    for line in result.stdout.splitlines():
        match = DATASET_PATTERN.search(line)

        if not match:
            continue

        dataset = match.group(1)
        taxon_name = dataset.rsplit("_odb", 1)[0].replace("_", " ")

        datasets[taxon_name.lower()] = dataset

    if not datasets:
        raise RuntimeError("No BUSCO datasets could be parsed from 'busco --list-datasets'.")

    return datasets


def get_shared_taxa(taxonomy):
    """Return taxa shared by all input species in lineage order."""
    shared_taxa = []

    for rank in taxonomy.columns:
        if rank in METADATA_COLUMNS:
            continue

        values = {str(value).strip() for value in taxonomy[rank] if str(value).strip()}

        if len(values) == 1:
            shared_taxa.append((rank, values.pop()))

    if not shared_taxa:
        raise ValueError("No shared taxonomic clade was found between input species.")

    return shared_taxa


def select_shared_busco_dataset(taxonomy, available_datasets):
    """Return the most specific BUSCO dataset shared by all input species."""
    shared_taxa = get_shared_taxa(taxonomy)

    for rank, taxon_name in reversed(shared_taxa):
        dataset = available_datasets.get(taxon_name.lower())

        if dataset:
            return {
                "dataset": dataset,
                "rank": rank,
                "taxon": taxon_name,
            }

    raise ValueError("No BUSCO dataset matches the shared taxonomy of the input species.")


def main():
    args = parse_args()

    taxonomy = pd.read_csv(args.taxonomy, sep="\t", dtype=str, keep_default_na=False)
    available_datasets = list_busco_datasets()
    selected = select_shared_busco_dataset(taxonomy, available_datasets)

    if args.output:
        with args.output.open("w", encoding="utf-8") as handle:
            handle.write(f"{selected['dataset']}\n")
    else:
        print(selected["dataset"])


if __name__ == "__main__":
    main()
