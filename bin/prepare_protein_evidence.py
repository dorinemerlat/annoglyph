#!/usr/bin/env python3
"""Prepare OrthoDB and UniProt protein evidence for gene annotation."""

import argparse
import json
import csv
import gzip
import shutil
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from html.parser import HTMLParser
from pathlib import Path

import pandas as pd
from Bio import SeqIO


ORTHODB_URL = "https://bioinf.uni-greifswald.de/bioinf/partitioned_odb{version}/"
NCBI_ESEARCH_URL = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils/esearch.fcgi"
UNIPROT_SEARCH_URL = "https://rest.uniprot.org/uniprotkb/search"

METADATA_COLUMNS = {
    "id",
    "name",
    "taxonomy",
    "taxid",
    "official_mnemonic",
    "annoglyph_mnemonic",
}


class FastaLinkParser(HTMLParser):
    """Extract downloadable FASTA files from an HTML page."""

    def __init__(self):
        super().__init__()
        self.files = []

    def handle_starttag(self, tag, attrs):
        if tag != "a":
            return

        href = dict(attrs).get("href", "")
        if href.endswith(".fa.gz"):
            self.files.append(Path(href).name)


def parse_args():
    parser = argparse.ArgumentParser(description="Prepare OrthoDB and UniProt protein evidence.")
    parser.add_argument("--evaluation", action="store_true", help="Select automatic evidence above the genus rank.")
    parser.add_argument("--taxonomy", required=True, type=Path, help="Taxonomy TSV generated by AnnoGlyph.")
    parser.add_argument("--orthodb-version", required=True, type=int, choices=[11, 12], help="OrthoDB partition version.")
    parser.add_argument("--min-sequences", type=int, default=100000, help="Minimum UniProtKB protein count required to select a taxonomic clade.")
    parser.add_argument("--max-sequences", type=int, default=0, help="Maximum total number of sequences retained in the combined protein set; 0 keeps all sequences.")
    parser.add_argument("--output", default=Path("protein_evidence.fa"), type=Path, help="Combined protein FASTA.")
    parser.add_argument("--metadata-output", default=Path("protein_evidence.tsv"), type=Path, help="Evidence metadata TSV.")
    parser.add_argument('--uniprot-release', default=None, help='Reject REST responses from a different UniProt release.')
    return parser.parse_args()


def open_request(request, timeout=300):
    """Retry temporary HTTP failures without hiding permanent errors."""
    for attempt in range(6):
        try:
            return urllib.request.urlopen(request, timeout=timeout)
        except urllib.error.HTTPError as error:
            if error.code not in (429, 500, 502, 503, 504) or attempt == 5:
                raise
            delay = 10 * (2 ** attempt)
            retry_after = error.headers.get('Retry-After') if error.headers else None
            if retry_after and retry_after.isdigit():
                delay = max(delay, int(retry_after))
            print(f'HTTP {error.code}; retrying in {delay}s ({attempt + 1}/5)', file=sys.stderr)
            error.close()
            time.sleep(delay)


def open_url(url, params=None, timeout=300):
    """Open a URL with an AnnoGlyph user agent."""
    if params:
        url = f"{url}?{urllib.parse.urlencode(params)}"

    request = urllib.request.Request(url, headers={"User-Agent": "AnnoGlyph/1.0"})
    return open_request(request, timeout=timeout)


def list_orthodb_partitions(version):
    """Return available OrthoDB partitions."""
    url = ORTHODB_URL.format(version=version)

    with open_url(url) as response:
        html = response.read().decode("utf-8")

    parser = FastaLinkParser()
    parser.feed(html)

    partitions = {}

    for filename in parser.files:
        clade = filename.removesuffix(".fa.gz")
        partitions[clade.lower()] = {
            "name": clade,
            "url": urllib.parse.urljoin(url, filename),
        }

    if not partitions:
        raise RuntimeError(f"No OrthoDB partitions found at {url}")

    return partitions


def get_shared_taxa(taxonomy):
    """Return taxa shared by all input species in lineage order."""
    shared_taxa = []

    for rank in taxonomy.columns:
        if rank in METADATA_COLUMNS:
            continue

        values = {str(value).strip() for value in taxonomy[rank] if str(value).strip()}

        if len(values) == 1:
            shared_taxa.append((rank, values.pop()))

    if not shared_taxa:
        raise ValueError("No shared taxonomic clade was found between input species.")

    return shared_taxa


def fetch_ncbi_taxid(scientific_name):
    """Resolve an NCBI taxid from an exact scientific name."""
    params = {
        "db": "taxonomy",
        "term": f'"{scientific_name}"[Scientific Name]',
        "retmode": "xml",
    }

    with open_url(NCBI_ESEARCH_URL, params) as response:
        root = ET.fromstring(response.read())

    taxid = root.findtext(".//Id")

    if not taxid:
        raise ValueError(f"NCBI taxid not found for '{scientific_name}'.")

    return taxid


def count_uniprot_proteins(taxid):
    """Return the number of UniProtKB proteins assigned to a taxonomic clade."""
    params = {
        "query": f"taxonomy_id:{taxid}",
        "format": "list",
        "size": 1,
    }
    url = f"{UNIPROT_SEARCH_URL}?{urllib.parse.urlencode(params)}"
    request = urllib.request.Request(url, headers={"User-Agent": "AnnoGlyph/1.0"})

    with open_request(request, timeout=60) as response:
        total = response.headers.get("X-Total-Results")

    if total is None:
        raise RuntimeError(f"UniProtKB did not return a result count for taxid {taxid}.")

    return int(total)


def select_uniprot_clade(taxonomy, min_sequences):
    """Select the most specific shared clade with enough UniProtKB proteins."""
    shared_taxa = get_shared_taxa(taxonomy)
    last_candidate = None

    for rank, name in reversed(shared_taxa):
        taxid = fetch_ncbi_taxid(name)
        protein_count = count_uniprot_proteins(taxid)

        print(
            f"UniProtKB {name} ({rank}, taxid {taxid}): {protein_count:,} proteins",
            file=sys.stderr,
        )

        last_candidate = {
            "name": name,
            "rank": rank,
            "taxid": taxid,
            "protein_count": protein_count,
        }

        if protein_count >= min_sequences:
            return last_candidate

    if last_candidate:
        print(
            f"WARNING: No shared clade reached {min_sequences:,} UniProtKB proteins. "
            f"Using the broadest shared clade: {last_candidate['name']}.",
            file=sys.stderr,
        )
        return last_candidate

    raise ValueError("No shared taxonomic clade was found.")


def select_orthodb_partition(taxonomy, partitions):
    """Select the most specific available OrthoDB partition."""
    for rank, name in reversed(get_shared_taxa(taxonomy)):
        partition = partitions.get(name.lower())

        if partition:
            return partition

    available = ", ".join(sorted(partition["name"] for partition in partitions.values()))
    raise ValueError(
        "No OrthoDB partition was found for the shared taxonomy. "
        f"Available partitions: {available}"
    )


def download_orthodb(partition, output):
    """Download and decompress an OrthoDB partition."""
    print(f"Downloading OrthoDB partition: {partition['name']}", file=sys.stderr)

    with open_url(partition["url"]) as response:
        with gzip.GzipFile(fileobj=response) as compressed:
            with output.open("wb") as handle:
                shutil.copyfileobj(compressed, handle)


def get_next_link(link_header):
    """Return the next URL from an HTTP Link header."""
    if not link_header:
        return None

    for link in link_header.split(","):
        url, *parameters = link.split(";")

        if any(parameter.strip() == 'rel="next"' for parameter in parameters):
            return url.strip()[1:-1]

    return None


def download_uniprot(taxid, output, expected_release=None):
    """Download UniProtKB proteins assigned to a taxonomic clade."""
    params = {
        "query": f"taxonomy_id:{taxid}",
        "format": "fasta",
        "size": 500,
    }
    url = f"{UNIPROT_SEARCH_URL}?{urllib.parse.urlencode(params)}"
    sequence_count = 0
    observed_release = None

    print(f"Downloading UniProtKB proteins for taxid {taxid}", file=sys.stderr)

    with output.open("wb") as handle:
        while url:
            request = urllib.request.Request(
                url,
                headers={
                    "Accept": "text/plain",
                    "User-Agent": "AnnoGlyph/1.0",
                },
            )

            with open_request(request, timeout=300) as response:
                release = response.headers.get('X-UniProt-Release')
                if expected_release and release != expected_release:
                    raise ValueError(f'Expected UniProt release {expected_release}, received {release}')
                if observed_release and release != observed_release:
                    raise ValueError('UniProt release changed while downloading evidence')
                observed_release = release
                output.with_suffix('.release.json').write_text(json.dumps({'source': 'UniProtKB REST', 'release': release, 'release_date': response.headers.get('X-UniProt-Release-Date')}, indent=2) + '\n')
                content = response.read()
                handle.write(content)
                sequence_count += content.count(b">")
                url = get_next_link(response.headers.get("Link"))

            print(f"Downloaded {sequence_count:,} UniProtKB proteins.", file=sys.stderr)

    if sequence_count == 0:
        raise RuntimeError(f"No UniProtKB proteins were found for taxid {taxid}.")


def truncate_fasta(path, max_sequences):
    """Keep at most max_sequences FASTA records."""
    temporary_output = path.with_name(f"{path.name}.tmp")

    with temporary_output.open("w", encoding="utf-8") as handle:
        records = (
            record
            for index, record in enumerate(SeqIO.parse(path, "fasta"))
            if index < max_sequences
        )
        SeqIO.write(records, handle, "fasta")

    temporary_output.replace(path)


def concatenate_fastas(inputs, output):
    """Concatenate FASTA files."""
    with output.open("wb") as destination:
        for path in inputs:
            with path.open("rb") as source:
                shutil.copyfileobj(source, destination)


def count_sequences(path):
    """Count FASTA records."""
    with path.open("rb") as handle:
        return sum(line.startswith(b">") for line in handle)


def write_metadata(path, version, orthodb_partition, uniprot_clade, orthodb, uniprot, combined):
    """Write protein evidence metadata."""
    rows = [
        {
            "source": "OrthoDB",
            "clade": orthodb_partition["name"],
            "rank": "",
            "taxid": "",
            "version": version,
            "sequences": count_sequences(orthodb),
            "file": orthodb.name,
        },
        {
            "source": "UniProtKB",
            "clade": uniprot_clade["name"],
            "rank": uniprot_clade["rank"],
            "taxid": uniprot_clade["taxid"],
            "version": "",
            "sequences": count_sequences(uniprot),
            "file": uniprot.name,
        },
        {
            "source": "combined",
            "clade": "",
            "rank": "",
            "taxid": "",
            "version": "",
            "sequences": count_sequences(combined),
            "file": combined.name,
        },
    ]

    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=rows[0].keys(), delimiter="\t")
        writer.writeheader()
        writer.writerows(rows)


def main():
    args = parse_args()
    taxonomy = pd.read_csv(args.taxonomy, sep="\t", dtype=str, keep_default_na=False)
    if args.evaluation:
        # Evidence must include relatives outside the target genera.
        if 'genus' not in taxonomy.columns:
            raise ValueError('Evaluation requires a genus column in the taxonomy table')
        taxonomy = taxonomy.iloc[:, :taxonomy.columns.get_loc('genus')]
    partitions = list_orthodb_partitions(args.orthodb_version)

    uniprot_clade = select_uniprot_clade(taxonomy, args.min_sequences)
    orthodb_partition = select_orthodb_partition(taxonomy, partitions)

    orthodb_output = Path(f"{orthodb_partition['name'].lower()}_odb{args.orthodb_version}.fa")
    uniprot_output = Path(f"{uniprot_clade['name'].lower()}_uniprot.fa")

    print(
        f"Selected UniProt evidence clade: {uniprot_clade['name']} "
        f"({uniprot_clade['rank']}, taxid {uniprot_clade['taxid']}, "
        f"{uniprot_clade['protein_count']:,} proteins)",
        file=sys.stderr,
    )
    print(
        f"Selected OrthoDB partition: {orthodb_partition['name']} "
        f"(OrthoDB {args.orthodb_version})",
        file=sys.stderr,
    )

    download_orthodb(orthodb_partition, orthodb_output)
    download_uniprot(uniprot_clade["taxid"], uniprot_output, args.uniprot_release)

    if args.max_sequences:
        orthodb_limit = args.max_sequences // 2
        uniprot_limit = args.max_sequences - orthodb_limit
        truncate_fasta(orthodb_output, orthodb_limit)
        truncate_fasta(uniprot_output, uniprot_limit)

    concatenate_fastas([orthodb_output, uniprot_output], args.output)

    write_metadata(
        args.metadata_output,
        args.orthodb_version,
        orthodb_partition,
        uniprot_clade,
        orthodb_output,
        uniprot_output,
        args.output,
    )

    print(f"Final protein evidence set: {count_sequences(args.output):,} sequences", file=sys.stderr)


if __name__ == "__main__":
    main()
