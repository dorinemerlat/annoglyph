#!/usr/bin/env python3
"""Download OrthoDB and UniProt protein evidence for gene annotation."""

import argparse
import csv
import gzip
import re
import shutil
import sys
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from html.parser import HTMLParser
from pathlib import Path

import pandas as pd
from Bio import SeqIO

ORTHODB_URL = "https://bioinf.uni-greifswald.de/bioinf/partitioned_odb{version}/"
NCBI_ESEARCH_URL = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils/esearch.fcgi"
NCBI_EFETCH_URL = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils/efetch.fcgi"
UNIPROT_SEARCH_URL = "https://rest.uniprot.org/uniprotkb/search"

METADATA_COLUMNS = {
    "id",
    "name",
    "taxonomy",
    "taxid",
    "official_mnemonic",
    "exogap_mnemonic",
}

RANK_ORDER = [
    "species",
    "genus",
    "family",
    "order",
    "class",
    "subphylum",
    "phylum",
    "subkingdom",
    "kingdom",
    "domain",
    "superkingdom",
]


class FastaLinkParser(HTMLParser):
    """Extract downloadable FASTA files from an HTML page."""

    def __init__(self):
        super().__init__()
        self.files = []

    def handle_starttag(self, tag, attrs):
        if tag != "a":
            return

        href = dict(attrs).get("href", "")

        if href.endswith(".fa.gz"):
            self.files.append(Path(href).name)


def parse_args():
    parser = argparse.ArgumentParser(description="Prepare OrthoDB and UniProt protein evidence.")
    parser.add_argument("--taxonomy", required=True, type=Path, help="Taxonomy TSV generated by EXOGAP.")
    parser.add_argument("--busco-datasets", required=True, type=Path, help="TSV containing id and busco_dataset columns.")
    parser.add_argument(
        "--minimum-rank",
        default="class",
        choices=RANK_ORDER,
        help="Most specific taxonomic rank allowed for UniProt protein evidence.",
    )
    parser.add_argument(
        "--max-sequences",
        type=int,
        default=0,
        help="Maximum total number of sequences retained in the combined protein set; 0 keeps all sequences.",
    )
    parser.add_argument("--output", default=Path("protein_evidence.fa"), type=Path, help="Combined protein FASTA.")
    parser.add_argument("--metadata-output", default=Path("protein_evidence.tsv"), type=Path, help="Evidence metadata TSV.")
    return parser.parse_args()


def open_url(url, params=None, timeout=300):
    """Open a URL with an EXOGAP user agent."""
    if params:
        url = f"{url}?{urllib.parse.urlencode(params)}"

    request = urllib.request.Request(
        url,
        headers={
            "Accept": "text/plain",
            "User-Agent": "EXOGAP/1.0",
        },
    )
    return urllib.request.urlopen(request, timeout=timeout)


def read_busco_datasets(path):
    """Return BUSCO datasets and the compatible OrthoDB version."""
    table = pd.read_csv(path, sep="\t", dtype=str)

    if not {"id", "busco_dataset"}.issubset(table.columns):
        raise ValueError("BUSCO dataset table must contain 'id' and 'busco_dataset' columns.")

    datasets = table["busco_dataset"].dropna().unique().tolist()

    if not datasets:
        raise ValueError("No BUSCO dataset was found in the input table.")

    versions = []

    for dataset in datasets:
        match = re.search(r"_odb(\d+)$", dataset, flags=re.IGNORECASE)

        if not match:
            raise ValueError(f"Cannot determine the OrthoDB version from '{dataset}'.")

        versions.append(int(match.group(1)))

    orthodb_version = 12 if all(version >= 12 for version in versions) else 11
    return datasets, orthodb_version


def list_orthodb_partitions(version):
    """Return available OrthoDB partitions."""
    url = ORTHODB_URL.format(version=version)

    with open_url(url) as response:
        html = response.read().decode("utf-8")

    parser = FastaLinkParser()
    parser.feed(html)

    partitions = {}

    for filename in parser.files:
        clade = filename.removesuffix(".fa.gz")
        partitions[clade.lower()] = {
            "name": clade,
            "filename": filename,
            "url": urllib.parse.urljoin(url, filename),
        }

    if not partitions:
        raise RuntimeError(f"No OrthoDB partitions found at {url}")

    return partitions


def get_rank_columns(taxonomy):
    """Return taxonomy rank columns in root-to-species order."""
    return [column for column in taxonomy.columns if column not in METADATA_COLUMNS]


def get_shared_taxa(taxonomy):
    """Return taxa shared by all species, indexed by rank."""
    shared_taxa = {}

    for rank in get_rank_columns(taxonomy):
        values = {
            str(value).strip()
            for value in taxonomy[rank]
            if str(value).strip()
        }

        if len(values) == 1:
            shared_taxa[rank] = values.pop()

    return shared_taxa


def extract_busco_clade(datasets):
    """Return the shared clade encoded in the BUSCO dataset names."""
    clades = {
        re.sub(r"_odb\d+$", "", dataset, flags=re.IGNORECASE).lower()
        for dataset in datasets
    }

    if len(clades) != 1:
        raise ValueError(
            "All genomes must use BUSCO datasets from the same taxonomic clade. "
            f"Found: {', '.join(sorted(clades))}"
        )

    return clades.pop()


def fetch_ncbi_taxid(scientific_name):
    """Resolve an NCBI taxid from an exact scientific name."""
    params = {
        "db": "taxonomy",
        "term": f'"{scientific_name}"[Scientific Name]',
        "retmode": "xml",
    }

    with open_url(NCBI_ESEARCH_URL, params) as response:
        root = ET.fromstring(response.read())

    taxids = [element.text for element in root.findall(".//Id") if element.text]

    if not taxids:
        raise ValueError(f"NCBI taxid not found for '{scientific_name}'.")

    taxid = taxids[0]

    with open_url(
        NCBI_EFETCH_URL,
        {"db": "taxonomy", "id": taxid, "retmode": "xml"},
    ) as response:
        root = ET.fromstring(response.read())

    returned_name = root.findtext(".//Taxon/ScientificName", default="")

    if returned_name.lower() != scientific_name.lower():
        raise ValueError(
            f"NCBI returned '{returned_name}' instead of '{scientific_name}'."
        )

    return taxid


def select_evidence_clade(taxonomy, busco_clade, minimum_rank):
    """Select the UniProt clade from the BUSCO clade and minimum rank."""
    shared_taxa = get_shared_taxa(taxonomy)
    busco_rank = None
    busco_name = None

    for rank, name in shared_taxa.items():
        if name.lower() == busco_clade.lower():
            busco_rank = rank
            busco_name = name
            break

    if busco_rank is None:
        raise ValueError(
            f"BUSCO clade '{busco_clade}' was not found in the shared taxonomy."
        )

    if busco_rank not in RANK_ORDER:
        raise ValueError(f"Unsupported BUSCO taxonomic rank: {busco_rank}")

    busco_index = RANK_ORDER.index(busco_rank)
    minimum_index = RANK_ORDER.index(minimum_rank)
    selected_rank = busco_rank

    if busco_index < minimum_index:
        for rank in RANK_ORDER[minimum_index:]:
            if rank in shared_taxa:
                selected_rank = rank
                break
        else:
            raise ValueError(
                f"No shared taxon was found at or above rank '{minimum_rank}'."
            )

    selected_name = shared_taxa[selected_rank]

    return {
        "name": selected_name,
        "rank": selected_rank,
        "taxid": fetch_ncbi_taxid(selected_name),
        "busco_name": busco_name,
        "busco_rank": busco_rank,
    }


def select_orthodb_partition(taxonomy, partitions, start_clade):
    """Select the most specific available OrthoDB partition."""
    shared_taxa = get_shared_taxa(taxonomy)
    lineage = list(shared_taxa.values())
    lineage_lower = [name.lower() for name in lineage]

    if start_clade.lower() not in lineage_lower:
        raise ValueError(
            f"Starting clade '{start_clade}' was not found in the shared taxonomy."
        )

    start_index = lineage_lower.index(start_clade.lower())

    # Search from the starting clade towards broader ancestral taxa.
    for name in reversed(lineage[: start_index + 1]):
        partition = partitions.get(name.lower())

        if partition:
            return partition

    available = ", ".join(
        sorted(partition["name"] for partition in partitions.values())
    )
    raise ValueError(
        f"No OrthoDB partition was found for '{start_clade}' or its ancestors. "
        f"Available partitions: {available}"
    )


def download_orthodb(partition, output):
    """Download and decompress an OrthoDB partition."""
    print(f"Downloading OrthoDB partition: {partition['name']}", file=sys.stderr)

    with open_url(partition["url"]) as response:
        with gzip.GzipFile(fileobj=response) as compressed:
            with output.open("wb") as handle:
                shutil.copyfileobj(compressed, handle)


def get_next_link(link_header):
    """Return the next URL from an HTTP Link header."""
    if not link_header:
        return None

    for link in link_header.split(","):
        url, *parameters = link.split(";")

        if any(parameter.strip() == 'rel="next"' for parameter in parameters):
            return url.strip()[1:-1]

    return None


def download_uniprot(taxid, output):
    """Download UniProtKB proteins assigned to a taxonomic clade."""
    params = {
        "query": f"taxonomy_id:{taxid}",
        "format": "fasta",
        "size": 500,
    }
    url = f"{UNIPROT_SEARCH_URL}?{urllib.parse.urlencode(params)}"
    sequence_count = 0

    print(f"Downloading UniProtKB proteins for taxid {taxid}", file=sys.stderr)

    with output.open("wb") as handle:
        while url:
            request = urllib.request.Request(
                url,
                headers={
                    "Accept": "text/plain",
                    "User-Agent": "EXOGAP/1.0",
                },
            )

            with urllib.request.urlopen(request, timeout=300) as response:
                content = response.read()
                handle.write(content)
                sequence_count += content.count(b">")
                url = get_next_link(response.headers.get("Link"))

            print(
                f"Downloaded {sequence_count:,} UniProtKB proteins.",
                file=sys.stderr,
            )

    if sequence_count == 0:
        raise RuntimeError(f"No UniProtKB proteins were found for taxid {taxid}.")


def concatenate_fastas(inputs, output):
    """Concatenate FASTA files."""
    with output.open("wb") as destination:
        for path in inputs:
            with path.open("rb") as source:
                shutil.copyfileobj(source, destination)


def count_sequences(path):
    """Count FASTA records without loading sequences into memory."""
    count = 0

    with path.open("rb") as handle:
        for line in handle:
            if line.startswith(b">"):
                count += 1

    return count


def write_metadata(
    path,
    datasets,
    version,
    orthodb_partition,
    uniprot_clade,
    orthodb,
    uniprot,
    combined,
):
    """Write protein evidence metadata."""
    rows = [
        {
            "source": "OrthoDB",
            "clade": orthodb_partition["name"],
            "rank": "",
            "taxid": "",
            "version": version,
            "busco_datasets": ",".join(datasets),
            "sequences": count_sequences(orthodb),
            "file": orthodb.name,
        },
        {
            "source": "UniProtKB",
            "clade": uniprot_clade["name"],
            "rank": uniprot_clade["rank"],
            "taxid": uniprot_clade["taxid"],
            "version": "",
            "busco_datasets": ",".join(datasets),
            "sequences": count_sequences(uniprot),
            "file": uniprot.name,
        },
        {
            "source": "combined",
            "clade": "",
            "rank": "",
            "taxid": "",
            "version": "",
            "busco_datasets": ",".join(datasets),
            "sequences": count_sequences(combined),
            "file": combined.name,
        },
    ]

    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=rows[0].keys(), delimiter="\t")
        writer.writeheader()
        writer.writerows(rows)


def truncate_fasta(input_fasta, output_fasta, max_sequences):
    """Write at most max_sequences FASTA records."""
    temporary_output = output_fasta.with_name(f"{output_fasta.name}.tmp")

    with temporary_output.open("w", encoding="utf-8") as handle:
        records = (
            record
            for index, record in enumerate(SeqIO.parse(input_fasta, "fasta"))
            if index < max_sequences
        )
        SeqIO.write(records, handle, "fasta")

    temporary_output.replace(output_fasta)


def main():
    args = parse_args()

    taxonomy = pd.read_csv(
        args.taxonomy,
        sep="\t",
        dtype=str,
        keep_default_na=False,
    )
    datasets, orthodb_version = read_busco_datasets(args.busco_datasets)
    partitions = list_orthodb_partitions(orthodb_version)
    busco_clade = extract_busco_clade(datasets)

    uniprot_clade = select_evidence_clade(
        taxonomy,
        busco_clade,
        minimum_rank=args.minimum_rank,
    )
    orthodb_partition = select_orthodb_partition(
        taxonomy,
        partitions,
        start_clade=busco_clade,
    )

    orthodb_name = orthodb_partition["name"].lower()
    uniprot_name = uniprot_clade["name"].lower()

    orthodb_output = Path(f"{orthodb_name}_odb{orthodb_version}.fa")
    uniprot_output = Path(f"{uniprot_name}_uniprot.fa")

    print(
        f"BUSCO clade: {uniprot_clade['busco_name']} "
        f"({uniprot_clade['busco_rank']})",
        file=sys.stderr,
    )
    print(
        f"UniProt evidence clade: {uniprot_clade['name']} "
        f"({uniprot_clade['rank']}, taxid {uniprot_clade['taxid']})",
        file=sys.stderr,
    )
    print(
        f"OrthoDB partition: {orthodb_partition['name']} "
        f"(OrthoDB {orthodb_version})",
        file=sys.stderr,
    )

    download_orthodb(orthodb_partition, orthodb_output)
    download_uniprot(uniprot_clade["taxid"], uniprot_output)
    
    if args.max_sequences:
        limit_orthodb = args.max_sequences // 2
        limit_uniprot = args.max_sequences - limit_orthodb
        truncate_fasta(orthodb_output, orthodb_output, limit_orthodb)
        truncate_fasta(uniprot_output, uniprot_output, limit_uniprot)

    concatenate_fastas([orthodb_output, uniprot_output], args.output)

    write_metadata(
        args.metadata_output,
        datasets,
        orthodb_version,
        orthodb_partition,
        uniprot_clade,
        orthodb_output,
        uniprot_output,
        args.output,
    )


if __name__ == "__main__":
    main()
